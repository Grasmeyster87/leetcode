/**
 * @param {string} s1
 * @param {string} s2
 * @return {boolean}
 */
var canBeEqual = function (s1, s2) {
    /**
     * Перевіряємо першу пару (індекси 0 та 2).
     * Вони рівні, якщо стоять на своїх місцях АБО якщо їх можна поміняти місцями.
     */
    const group1Match = (s1[0] === s2[0] && s1[2] === s2[2]) || 
                         (s1[0] === s2[2] && s1[2] === s2[0]);

    /**
     * Перевіряємо другу пару (індекси 1 та 3).
     * Логіка аналогічна.
     */
    const group2Match = (s1[1] === s2[1] && s1[3] === s2[3]) || 
                         (s1[1] === s2[3] && s1[3] === s2[1]);

    // Рядки можна зробити рівними, якщо обидві групи символів збігаються
    return group1Match && group2Match;
};
