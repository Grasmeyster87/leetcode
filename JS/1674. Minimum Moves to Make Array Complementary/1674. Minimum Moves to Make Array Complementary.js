/**
 * @param {number[]} nums
 * @param {number} limit
 * @return {number}
 */
var minMoves = function(nums, limit) {
    // Довжина масиву
    const n = nums.length;

    // Масив різниць (difference array) розміром 2*limit + 2
    // Індекс T означає цільову суму пар (nums[i] + nums[n-1-i] = T)
    // Можливі значення T: від 2 (мінімум: 1+1) до 2*limit (максимум: limit+limit)
    const diff = new Array(2 * limit + 2).fill(0);

    // Обробляємо кожну пару (nums[i], nums[n-1-i])
    for (let i = 0; i < n / 2; i++) {
        const a = nums[i];           // Лівий елемент пари
        const b = nums[n - 1 - i];   // Правий елемент пари

        // Для кожної пари (a, b) визначаємо скільки ходів потрібно
        // залежно від цільової суми T:
        //
        // 1) T ∈ [2, min(a,b)]  → потрібно 2 ходи (обидва елементи змінити)
        // 2) T ∈ [min(a,b)+1, a+b-1] → потрібно 1 хід (один елемент змінити)
        // 3) T = a+b            → потрібно 0 ходів (сума вже дорівнює T)
        // 4) T ∈ [a+b+1, max(a,b)+limit] → потрібно 1 хід
        // 5) T ∈ [max(a,b)+limit+1, 2*limit] → потрібно 2 ходи
        //
        // Використовуємо масив різниць для ефективного оновлення діапазонів:
        // Спочатку вважаємо що для всіх T потрібно 2 ходи,
        // потім віднімаємо 1 для діапазону де потрібен лише 1 хід,
        // і ще віднімаємо 1 для точки де 0 ходів.

        // Базово: для всіх T від 2 до 2*limit потрібно 2 ходи → додаємо +2 на [2]
        // (це вже зроблено: ми додамо 2 ходи для кожної пари на весь діапазон)

        // Діапазон де потрібен максимум 1 хід: [min(a,b)+1, max(a,b)+limit]
        // → віднімаємо 1 на початку діапазону, додаємо 1 після кінця
        diff[Math.min(a, b) + 1] -= 1;
        diff[Math.max(a, b) + limit + 1] += 1;

        // Точка де потрібно 0 ходів: T = a + b
        // → віднімаємо ще 1 на a+b, додаємо 1 на a+b+1
        diff[a + b] -= 1;
        diff[a + b + 1] += 1;
    }

    // Обчислюємо фактичну кількість ходів для кожного T
    // через префіксну суму масиву різниць
    let result = n;     // Початкове значення — максимум (n/2 пар × 2 ходи)
    let currentMoves = n; // Базові 2 ходи на кожну з n/2 пар = n ходів

    for (let T = 2; T <= 2 * limit; T++) {
        currentMoves += diff[T]; // Застосовуємо зміну з масиву різниць
        result = Math.min(result, currentMoves); // Оновлюємо мінімум
    }

    return result;
};

// Тести
console.log(minMoves([1,2,4,3], 4)); // Очікується: 1
console.log(minMoves([1,2,2,1], 2)); // Очікується: 2
console.log(minMoves([1,2,1,2], 2)); // Очікується: 0